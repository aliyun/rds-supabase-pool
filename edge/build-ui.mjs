import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "frontend", "dist");
const outDir = join(root, "edge", ".build");

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const assets = {};
for (const file of walk(dist)) {
  const key = relative(dist, file).split("\\").join("/");
  assets[key] = readFileSync(file).toString("base64");
}

if (!assets["index.html"]) throw new Error("frontend/dist/index.html 不存在，请先构建前端");

let html = Buffer.from(assets["index.html"], "base64").toString("utf8");
if (!html.includes("__POOL_API_BASE__")) {
  html = html.replace(
    "<head>",
    '<head><script>window.__POOL_API_BASE__="/functions/v1/pool-api/api";window.__POOL_UI_BASE__="/functions/v1/pool-ui";</script>',
  );
  assets["index.html"] = Buffer.from(html, "utf8").toString("base64");
}

const code = `// @ts-nocheck
// Generated by edge/build-ui.mjs. Do not edit by hand.

const ASSETS: Record<string, string> = ${JSON.stringify(assets)};

const MIME: Record<string, string> = {
  html: "text/html; charset=utf-8",
  js: "application/javascript; charset=utf-8",
  css: "text/css; charset=utf-8",
  json: "application/json",
  map: "application/json",
  svg: "image/svg+xml",
  png: "image/png",
  ico: "image/x-icon",
  txt: "text/plain; charset=utf-8",
  webmanifest: "application/manifest+json",
  woff: "font/woff",
  woff2: "font/woff2",
};

function decode(value: string): Uint8Array {
  const raw = atob(value);
  return Uint8Array.from(raw, (char) => char.charCodeAt(0));
}

Deno.serve({ port: Number(Deno.env.get("PORT") || 8000) }, (req) => {
  const url = new URL(req.url);
  const suffix = url.pathname.replace(/^.*\\/functions\\/v1\\/pool-ui/, "") || "/";
  const key = suffix === "/" ? "index.html" : suffix.replace(/^\\//, "");
  const asset = ASSETS[key];
  if (asset) {
    const ext = key.split(".").pop() || "";
    return new Response(decode(asset), {
      headers: {
        "content-type": MIME[ext] || "application/octet-stream",
        "cache-control": key === "index.html" ? "no-cache" : "public, max-age=31536000, immutable",
      },
    });
  }
  if (key.startsWith("assets/")) return new Response("Not found", { status: 404 });
  return new Response(decode(ASSETS["index.html"]), {
    headers: { "content-type": MIME.html, "cache-control": "no-cache" },
  });
});
`;

mkdirSync(outDir, { recursive: true });
const output = join(outDir, "pool-ui.ts");
writeFileSync(output, code);
console.log(`generated ${output} (${Object.keys(assets).length} assets, ${Math.round(code.length / 1024)} KB)`);
